function initialLanguage(): Language {
  if (!browser) return 'en';

  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === 'en' || stored === 'vi') return stored;

  return window.navigator.language.toLowerCase().startsWith('vi') ? 'vi' : 'en';
}

export const language = writable<Language>(initialLanguage());

if (browser) {
  language.subscribe((value) => {
    window.localStorage.setItem(STORAGE_KEY, value);
    document.documentElement.lang = value;
  });
}

export function setLanguage(value: Language) {
  language.set(value);
}

export function toggleLanguage(current: Language) {
  setLanguage(current === 'en' ? 'vi' : 'en');
}

export function t(lang: Language, key: string, params: Record<string, string | number> = {}): string {
  const template = translations[lang][key] ?? translations.en[key] ?? key;
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template
  );
}
